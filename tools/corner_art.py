"""Random character art in the bottom-left corner, shared by every game's
build script.

    from corner_art import write_art_js
    write_art_js(WEB)      # WEB = public/<game>/

Scans <WEB>/img/art/ and writes <WEB>/js/art.js, which picks one image at
random on each page load. Pages include it with
<script src="{rel}js/art.js"></script>; the look (size, opacity, desktop
only) lives in each game's css/style.css (.art-track / .corner-art). Drop
art in img/art/ and rebuild; an empty folder simply shows nothing.
"""
import json

EXTS = (".png", ".webp", ".jpg", ".jpeg", ".gif")


def write_art_js(web):
    art = web / "img" / "art"
    art.mkdir(parents=True, exist_ok=True)
    files = sorted(f.name for f in art.iterdir() if f.suffix.lower() in EXTS)
    (web / "js").mkdir(exist_ok=True)
    (web / "js" / "art.js").write_text(
        "// generated by tools/corner_art.py from img/art/ - don't edit\n"
        "(function () {\n"
        f"  var ART = {json.dumps(files, ensure_ascii=False)};\n"
        "  if (!ART.length) return;\n"
        "  var me = document.currentScript.src;\n"
        "  var img = document.createElement(\"img\");\n"
        "  img.className = \"corner-art\"; img.alt = \"\"; img.decoding = \"async\";\n"
        "  img.src = new URL(\"../img/art/\" + encodeURIComponent(ART[Math.floor(Math.random() * ART.length)]), me).href;\n"
        "  // the art sits in a track down the left edge that ends at the footer;\n"
        "  // CSS sticks it to the window bottom inside the track (no scroll handler)\n"
        "  var track = document.createElement(\"div\");\n"
        "  track.className = \"art-track\"; track.setAttribute(\"aria-hidden\", \"true\");\n"
        "  track.appendChild(img);\n"
        "  document.body.appendChild(track);\n"
        "  function fit() {\n"
        "    var footer = document.querySelector(\"footer.site\");\n"
        "    track.style.bottom = (footer ? footer.offsetHeight : 0) + \"px\";\n"
        "  }\n"
        "  document.addEventListener(\"DOMContentLoaded\", fit);\n"
        "  window.addEventListener(\"resize\", fit);\n"
        "})();\n", encoding="utf-8")
    print(f"corner art: {len(files)} image(s) in {art.relative_to(web.parent.parent)}/")
