VOCAB_KEYS = {}
p = ROOT / "study" / "fe4" / "vocab.txt"
if p.exists():
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            key = line.split("|")[0]
            base = key.split("#")[0]
            VOCAB_KEYS.setdefault(base, []).append(key)

script = json.loads((ROOT / "data" / "fe4_script.json").read_text(encoding="utf-8"))
tagger = fugashi.Tagger()
apply = "--apply" in sys.argv
slugs = [a for a in sys.argv[1:] if not a.startswith("--")]
cands = {}
for slug in slugs:
    boxes = [i for s in script[slug]["scenes"] for i in s["items"] if i["t"] == "box"]
    path = ROOT / "study" / "fe4" / f"{slug}.txt"
    rows = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            parts = line.split("|")
            n, v, g = parts[0], parts[1], parts[2] if len(parts) > 2 else ""
            rows[int(n)] = ([w for w in v.split(",") if w], g)
    for n, box in enumerate(boxes, 1):
        lines = ["".join(v for _, v in l) for l in box["lines"]]
        text = "".join(lines)
        words, g = rows.get(n, ([], ""))
        covered = []
        for w in words:
            s = w.split(">")[0].split("#")[0]
            i = text.find(s)
            if i >= 0:
                covered.append((i, i + len(s)))
        pos, new = 0, []
        for line in lines:
            for t in tagger(line):
                a = text.find(t.surface, pos)
                b = a + len(t.surface)
                pos = b
                f = t.feature
                base = f.orthBase or t.surface
                if f.pos1 not in CONTENT or t.surface in NAMES or re.fullmatch(r"[・！？…ー\W\d０-９A-Za-zA-Z]+", t.surface):
                    continue
                if base in SKIP:
                    continue
                if any(a < e and s < b for s, e in covered):
                    continue
                if apply and len(VOCAB_KEYS.get(base, [])) == 1:
                    key = VOCAB_KEYS[base][0]
                    new.append((a, key if t.surface == key else f"{t.surface}>{key}"))
                    covered.append((a, b))
                    continue
                c = cands.setdefault(base, [0, f.pos1, f.lemma, f"{slug}#{n}: {line}"])
                c[0] += 1
        if apply and new:
            allw = [(text.find(w.split(">")[0].split("#")[0]), w) for w in words] + new
            rows[n] = ([w for _, w in sorted(allw, key=lambda x: x[0])], g)
    if apply:
        path.write_text(
            "".join(f"{n}|{','.join(rows[n][0])}|{rows[n][1]}\n" for n in sorted(rows)),
            encoding="utf-8")

for base, (cnt, pos, lemma, ctx) in sorted(cands.items(), key=lambda kv: -kv[1][0]):
    print(f"{base}\t{cnt}\t{pos}\t{lemma}\t{ctx}")
print(len(cands), "uncovered base forms", file=sys.stderr)
